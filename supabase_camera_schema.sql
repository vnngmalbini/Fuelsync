-- Run this in the Supabase SQL editor.
-- The Django service-role client is the only writer/reader for camera frames.
insert into storage.buckets (id, name, public)
values ('camera-frames', 'camera-frames', false)
on conflict (id) do nothing;

create table if not exists public.camera_frames (
    id uuid primary key default gen_random_uuid(),
    camera_id text not null,
    object_path text not null unique,
    content_type text not null default 'image/jpeg',
    captured_at timestamptz not null default now(),
    captured_by_user_id text,
    captured_by_email text,
    captured_by_username text
);

create index if not exists camera_frames_camera_time_idx
    on public.camera_frames (camera_id, captured_at desc);

create table if not exists public.camera_access_logs (
    id bigint generated by default as identity primary key,
    camera_id text not null,
    user_id text not null,
    email text,
    username text,
    accessed_at timestamptz not null default now()
);

create index if not exists camera_access_logs_camera_time_idx
    on public.camera_access_logs (camera_id, accessed_at desc);

alter table public.camera_frames enable row level security;
alter table public.camera_access_logs enable row level security;
-- No public policies are intentional. Django uses the Supabase service-role key.

